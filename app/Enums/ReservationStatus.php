<?php

namespace App\Enums;

/**
 * Все допустимые состояния резерва в одном месте. Сохранённые значения совпадают со значениями в базе и ответах
 * пользователю.
 */
enum ReservationStatus: string
{
    // Количество удержано и ещё может быть подтверждено или возвращено.
    case Reserved = 'reserved';
    // Удержанное количество стало окончательным расходом.
    case Confirmed = 'confirmed';
    // Пользователь отменил резерв, и удержанное количество вернулось.
    case Cancelled = 'cancelled';
    // Срок истёк, обработка завершена и количество возвращено.
    case Expired = 'expired';
}
