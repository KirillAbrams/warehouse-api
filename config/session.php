<?php

/**
 * Стандартные настройки сохранения состояния входа между запросами браузера. Для данного запуска выбран способ,
 * который не сохраняет это состояние между запросами.
 */

use Illuminate\Support\Str;

return [

    // Где хранить состояние входа браузера. Для данного запуска выбрано хранение только внутри одного процесса
    // запроса.
    'driver' => env('SESSION_DRIVER', 'database'),

    // Сколько минут сохранять состояние входа и нужно ли завершать его при закрытии браузера.
    'lifetime' => (int) env('SESSION_LIFETIME', 120),

    'expire_on_close' => env('SESSION_EXPIRE_ON_CLOSE', false),

    // Нужно ли дополнительно защищать сохранённые значения состояния входа.
    'encrypt' => env('SESSION_ENCRYPT', false),

    // Папка для хранения состояния входа при выборе файлового способа.
    'files' => storage_path('framework/sessions'),

    // Соединение базы для хранения состояния входа при выборе такого способа.
    'connection' => env('SESSION_CONNECTION'),

    // Таблица для сохранённого состояния входа браузера.
    'table' => env('SESSION_TABLE', 'sessions'),

    // Хранилище временных значений для состояния входа.
    'store' => env('SESSION_STORE'),

    // Частота случайного запуска очистки устаревшего состояния входа.
    'lottery' => [2, 100],

    // Имя значения, с помощью которого браузер узнаёт свой сохранённый вход.
    'cookie' => env(
        'SESSION_COOKIE',
        Str::slug((string) env('APP_NAME', 'laravel')).'-session'
    ),

    // Пути сайта, для которых браузер передаёт значение входа.
    'path' => env('SESSION_PATH', '/'),

    // Адреса сайта, которым браузер передаёт значение входа.
    'domain' => env('SESSION_DOMAIN'),

    // Ограничение передачи значения входа защищённым соединением.
    'secure' => env('SESSION_SECURE_COOKIE'),

    // Запрет чтения значения входа программами страницы в браузере.
    'http_only' => env('SESSION_HTTP_ONLY', true),

    // Правила передачи значения входа при переходах с другого сайта.
    'same_site' => env('SESSION_SAME_SITE', 'lax'),

    // Раздельное хранение браузером значения входа для разных открытых сайтов.
    'partitioned' => env('SESSION_PARTITIONED_COOKIE', false),

    // Способ представления сохраняемых значений состояния входа.
    'serialization' => 'json',

];
